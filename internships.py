import streamlit as st
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.append(str(BASE_DIR))

from recommendation import get_internship_recommendations
from database import init_db
from utils import load_css, init_session_state

def render_internships_page():
    init_db()
    init_session_state()
    load_css()
    
    user_skills_list = st.session_state.get("user_skills") or st.session_state.get("skills") or ["Python", "SQL"]
    selected_career = st.session_state.get("selected_career", "Python Developer")
    
    st.markdown("""
        <div style="margin-bottom: 24px;">
            <h2 style="margin: 0; color: #F8FAFC;">💼 Recommended Internship Roles</h2>
            <p style="color: #94A3B8;">Find internship positions matched to your skills and preferred domain.</p>
        </div>
    """, unsafe_allow_html=True)
    
    st.info("ℹ️ **Notice:** These internship postings are intelligent domain-matched target profiles generated by our dataset recommendation engine to help you target suitable campus & off-campus internship roles.")
    
    # Filter Bar
    with st.expander("🔍 Filter Internship Preferences", expanded=True):
        col1, col2, col3 = st.columns(3)
        with col1:
            career_filter = st.selectbox("Target Career Domain", ["All", "Python Developer", "Data Analyst", "Data Scientist", "Machine Learning Engineer", "Web Developer", "Frontend Developer", "Backend Developer", "Full Stack Developer", "Java Developer", "Android Developer", "Cloud Engineer", "DevOps Engineer", "Cybersecurity Analyst"])
        with col2:
            location_filter = st.selectbox("Location Preference", ["Hybrid", "Remote", "Bangalore", "Hyderabad", "Pune", "Delhi NCR", "Mumbai"])
        with col3:
            mode_filter = st.selectbox("Work Mode", ["Remote/On-site", "Remote Only", "On-site Only", "Hybrid"])
            
    st.write("")
    
    target_role = career_filter if career_filter != "All" else selected_career
    try:
        internships = get_internship_recommendations(
            career_target=target_role,
            user_skills=user_skills_list,
            location_pref=location_filter,
            mode=mode_filter
        )
    except Exception as e:
        print(f"[Internships Warning] {e}")
        internships = []
        
    st.markdown(f"<h3 style='color: #F8FAFC;'>Available Internship Profiles ({len(internships)})</h3>", unsafe_allow_html=True)
    
    for idx, item in enumerate(internships, 1):
        skills_html = "".join([f'<span class="skill-badge">{s}</span>' for s in item['Skills_Required']])
        tools_html = "".join([f'<span style="background:rgba(255,255,255,0.06); color:#E2E8F0; padding:2px 8px; border-radius:12px; font-size:0.75rem; margin-right:4px;">{t}</span>' for t in item['Tools']])
        
        st.markdown(f"""
            <div class="glass-card">
                <div style="display: flex; justify-content: space-between; align-items: flex-start; margin-bottom: 12px;">
                    <div>
                        <h3 style="margin: 0; color: #38BDF8; font-size: 1.3rem;">{item['Internship_Title']}</h3>
                        <span style="color: #F8FAFC; font-weight: 600; font-size: 0.95rem;">Category: {item['Role']} | Industry: {item['Industry']}</span>
                    </div>
                    <span style="background: rgba(99, 102, 241, 0.2); color: #818CF8; border: 1px solid rgba(99, 102, 241, 0.4); padding: 4px 12px; border-radius: 20px; font-weight: 700; font-size: 0.8rem;">{item['Mode']}</span>
                </div>
                <p style="color: #94A3B8; font-size: 0.9rem; margin-bottom: 14px;">{item['Description']}</p>
                <div style="display: grid; grid-template-columns: 1fr 1fr 1fr; gap: 12px; background: rgba(15,23,42,0.5); padding: 12px; border-radius: 10px; margin-bottom: 14px;">
                    <div><strong style="color:#CBD5E1; font-size:0.75rem;">LOCATION:</strong><br><span style="color:#F8FAFC; font-size:0.85rem;">📍 {item['Location']}</span></div>
                    <div><strong style="color:#CBD5E1; font-size:0.75rem;">DURATION:</strong><br><span style="color:#F8FAFC; font-size:0.85rem;">⏳ {item['Duration']}</span></div>
                    <div><strong style="color:#CBD5E1; font-size:0.75rem;">STIPEND:</strong><br><span style="color:#10B981; font-weight:700; font-size:0.85rem;">💰 {item['Stipend_Range']}</span></div>
                </div>
                <div style="margin-bottom: 14px;">
                    <strong style="color: #CBD5E1; font-size: 0.8rem; display: block; margin-bottom: 4px;">REQUIRED SKILLS & TOOLS:</strong>
                    {skills_html} {tools_html}
                </div>
            </div>
        """, unsafe_allow_html=True)
        
        c1, c2 = st.columns([1, 4])
        with c1:
            if st.button(f"Save & Apply", key=f"btn_apply_{idx}"):
                st.success(f"Saved {item['Internship_Title']} to your profile!")

if __name__ == "__main__":
    render_internships_page()
